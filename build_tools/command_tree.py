"""Generate the Markdown command reference from the expanded CLI schemas."""

import argparse
import json
from pathlib import Path
import tempfile

from build_tools.schema_builder import ROOT, SchemaBuildError, build_schemas


OUTPUT = ROOT / 'docs' / 'users' / 'command-tree.md'
WIDTH = 100


def value_choices(node):
    """Show declared choices and hint placeholders, without querying a live router."""
    values = list(node.get('choices', {}))
    values.extend(node.get('choices_hint', ()))
    values.extend(node.get('hints', {}))

    # Hint-only choices are suggestions, not a closed vocabulary.
    if not node.get('choices') and not node.get('hints'):
        values.append('name' if node['kind'] == 'tag_node' else 'value')

    return list(dict.fromkeys(value.removeprefix('<').removesuffix('>') for value in values))


def path_suffix(name, node):
    """Describe the shared parser entry points referenced by control schemas."""
    target = node.get('path')
    if target == 'configuration':
        return ' <configuration-path>'
    if target in {'rename', 'copy'}:
        return ' <source-path> to <destination-path>'
    if target == 'load':
        return ' [replace] [set] <file>'
    if target == 'operational':
        return ' <command> [arguments ...]' if name == 'shellcmd' else ' <operational-command>'
    if node.get('command') in ('show', 'running', 'candidate'):
        return ' [<configuration-path>]'
    return ''


def node_lines(name, node, prefix, continuation, width):
    """Wrap between choices and retain the tree connector on every continuation."""
    valued = node['kind'] in {'leaf_node', 'tag_node'} and not node.get('valueless')
    if not valued:
        return [prefix + name + path_suffix(name, node)]

    join = node.get('joinable')
    join_negation = isinstance(join, dict) and join.get('negatable')
    head = '' if node.get('positional') else name + (' [not]' if node.get('negatable') or join_negation else '') + ' '
    if node.get('optional_value'):
        head += '['
    head += '<'
    tail = '>' + (']' if node.get('optional_value') else '')
    choices = value_choices(node)
    padding = continuation + ' ' * len(head)
    line = prefix + head
    lines = []
    has_value = False

    for index, choice in enumerate(choices):
        fragment = choice + ('|' if index < len(choices) - 1 else tail)
        if has_value and len(line) + len(fragment) > width:
            lines.append(line)
            line = padding
        line += fragment
        has_value = True

    suffix = ''
    if node.get('joinable'):
        suffix += ' [and [not] <value> ...]' if join_negation else ' [and <value> ...]'
    if node.get('rest'):
        suffix += ' [arguments ...]'
    if suffix and len(line) + len(suffix) > width:
        lines.append(line)
        line = padding + suffix.lstrip()
    else:
        line += suffix
    lines.append(line)
    return lines


def render_tree(label, root, width=WIDTH):
    lines = [label]

    def visit(node, prefix):
        children = sorted(node.get('children', {}).items())
        for index, (name, child) in enumerate(children):
            last = index == len(children) - 1
            branch = prefix + ('└── ' if last else '├── ')
            continuation = prefix + ('    ' if last else '│   ')
            lines.extend(node_lines(name, child, branch, continuation, width))
            visit(child, continuation)

    visit(root, '')
    return '\n'.join(lines)


def generate(source=ROOT / 'schemas'):
    # Use the same include expansion and validation as package/schema builds.
    with tempfile.TemporaryDirectory(prefix='nvyr-command-tree-') as directory:
        build_schemas(source=source, output=directory)
        trees = {name: json.loads((Path(directory) / f'{name}.json').read_text(encoding='utf-8'))
                 for name in ('configuration', 'control', 'operational', 'pipelines')}

    sections = [
        ('Configuration paths', 'set', 'configuration'),
        ('Configuration-mode commands', 'configuration mode', 'control'),
        ('Operational commands', 'operational mode', 'operational'),
        ('Pipe modifiers', '|', 'pipelines'),
    ]
    text = [
        '# nVyR command tree',
        '',
        'Generated from the current YAML schemas. Do not edit this file by hand.',
        'Regenerate with `python -m build_tools.command_tree`; verify with',
        '`python -m build_tools.command_tree --check`.',
        '',
        '- `<...>` denotes a value; `|` inside it separates alternatives.',
        '  Alternatives include declared choices and value hints, not live suggestions.',
        '- `configuration mode` and `operational mode` are section labels, not commands.',
        '- `[...]` denotes optional input. `[not]` excludes the following value.',
        '- `[and <value> ...]` joins more values using the same choices as the first.',
        '- Multi-value settings accept repeated commands. Anchored sections also allow',
        '  sibling settings on one line; the tree shows their configuration hierarchy.',
        '- Optional operational tag values may be omitted to reach their child commands.',
        '- A value-only operational branch is positional: enter the value without a keyword.',
        '- `<configuration-path>` refers to the configuration tree below; paths can be',
        '  relative to the current `edit` context. Copy/rename use compatible tag instances.',
        '- `<operational-command>` refers to the operational tree. `run` exposes it in',
        '  configuration mode. Existing permissions and cross-field checks still apply.',
        '- Pipe modifiers apply only to supported, non-streaming output.',
        '',
        'Choices wrap explicitly at 100 columns where possible, never inside a value.',
        'Continuation lines align with the first value and retain the tree connectors.',
    ]
    for title, label, key in sections:
        text.extend(['', f'## {title}', '', '```text', render_tree(label, trees[key]), '```'])
    return '\n'.join(text) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the command tree is missing or stale')
    args = parser.parse_args()

    try:
        expected = generate()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != expected:
                raise ValueError('docs/users/command-tree.md is missing or stale; run python -m build_tools.command_tree')
        else:
            OUTPUT.write_text(expected, encoding='utf-8', newline='\n')
    except (SchemaBuildError, ValueError, OSError) as error:
        parser.exit(1, f'Command tree generation failed: {error}\n')


if __name__ == '__main__':
    main()
