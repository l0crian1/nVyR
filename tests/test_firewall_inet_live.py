from tests.test_firewall_maps_live import isolated, pytestmark


def packet_acceptance(family):
    """Verify a neutral rule overrides an IP default, then falls through when removed."""
    isolated(f'family = {family!r}\n' + '''
from smoketests.firewall_support import send_firewall_udp
from smoketests.assertions import assert_firewall_rule_packets
run('ip', 'link', 'set', 'lo', 'up')
tree = {'firewall': {
    'inet': {'input': {'filter': {'rule': {'10': {
        'protocol': ['udp'], 'destination-port': ['53098'], 'action': 'accept', 'counter': {},
    }}}}},
    family: {'input': {'filter': {'default-action': 'drop'}}},
}}
apply(tree)
assert send_firewall_udp(2, family=family) == 2
assert_firewall_rule_packets('input', 10, 2)
assert_firewall_rule_packets(family + '_input', 'default', 0)
del tree['firewall']['inet']
apply(tree)
assert send_firewall_udp(1, family=family) == 0
assert_firewall_rule_packets(family + '_input', 'default', 1)
''')


def test_ipv4_neutral_accept_and_fallthrough():
    """IPv4 reaches direct inet rules before its ordinary default verdict."""
    packet_acceptance('ipv4')


def test_ipv6_neutral_accept_and_fallthrough():
    """IPv6 shares the exact same rule and follows its own dispatch on a miss."""
    packet_acceptance('ipv6')


def reject_response(family):
    """Capture the actual family-specific reply generated by an ICMPX verdict."""
    isolated(f'family = {family!r}\n' + '''
import socket
run('ip', 'link', 'set', 'lo', 'up')
af = socket.AF_INET if family == 'ipv4' else socket.AF_INET6
address = '127.0.0.1' if family == 'ipv4' else '::1'
protocol = socket.IPPROTO_ICMP if family == 'ipv4' else socket.IPPROTO_ICMPV6
tree = {'firewall': {'inet': {'input': {'filter': {'rule': {'10': {
    'action': 'reject', 'protocol': ['udp'], 'destination-port': ['53021'],
    'reject-response': 'admin-prohibited',
}}}}}}}
apply(tree)
with socket.socket(af, socket.SOCK_RAW, protocol) as capture:
    capture.settimeout(1)
    with socket.socket(af, socket.SOCK_DGRAM) as sender:
        sender.sendto(b'reject test', (address, 53021))
    packet = capture.recv(4096)
offset = (packet[0] & 15) * 4 if family == 'ipv4' else 0
assert tuple(packet[offset:offset + 2]) == ((3, 13) if family == 'ipv4' else (1, 1))
''')


def test_ipv4_icmpx_response():
    """The shared admin-prohibited response uses ICMP type 3/code 13 for IPv4."""
    reject_response('ipv4')


def test_ipv6_icmpx_response():
    """The same rule emits ICMPv6 type 1/code 1 for IPv6."""
    reject_response('ipv6')


